const bbox = (poly) => {
  let a = 180, b = -180, c = 90, d = -90;
  for (const [lon, lat] of poly) {
    if (lon < a) a = lon; if (lon > b) b = lon;
    if (lat < c) c = lat; if (lat > d) d = lat;
  }
  return [a, b, c, d];
};
const LAND_BOX = LAND.map(bbox);
const HOLE_BOX = HOLES.map(bbox);

export function inPolygon(lon, lat, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const inBox = (b, lon, lat) => lon >= b[0] && lon <= b[1] && lat >= b[2] && lat <= b[3];

export function isLand(lon, lat) {
  let land = false;
  for (let i = 0; i < LAND.length; i++) {
    if (inBox(LAND_BOX[i], lon, lat) && inPolygon(lon, lat, LAND[i])) { land = true; break; }
  }
  if (!land) return false;
  for (let i = 0; i < HOLES.length; i++) {
    if (inBox(HOLE_BOX[i], lon, lat) && inPolygon(lon, lat, HOLES[i])) return false;
  }
  return true;
}

// Seeded random (har baar wahi dots)
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * Zameen par dots: Float32Array, har dot ke 4 numbers [lat(rad), lon(rad), roshni 0..1, phase].
 * "City lights" jaisa asar: zyada tar dim, kuch jagah (smooth noise) par jhund aur chamak.
 */
export function landPoints(candidates = 210000, seed = 7) {
  const rnd = mulberry32(seed);
  const out = [];
  const D2R = Math.PI / 180;
  for (let n = 0; n < candidates; n++) {
    const lat = Math.asin(2 * rnd() - 1) / D2R;
    const lon = rnd() * 360 - 180;
    if (!isLand(lon, lat)) continue;
    // smooth "aabadi" noise: kuch ilaaqay roshan
    const cluster = 0.5 + 0.25 * Math.sin(lon * 0.21 + lat * 0.13) + 0.25 * Math.sin(lon * 0.07 - lat * 0.31 + 1.7);
    const keep = 0.35 + 0.65 * cluster;
    if (rnd() > keep) continue;
    const bright = Math.min(1, 0.12 + Math.pow(rnd(), 3.2) * 1.15 * (0.5 + cluster));
    out.push(lat * D2R, lon * D2R, bright, rnd() * 6.2832);
  }
  return Float32Array.from(out);
}
